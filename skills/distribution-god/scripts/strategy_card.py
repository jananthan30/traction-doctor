# fonts with close to these metrics on macOS, Windows, and Linux machines with
# Arial or Liberation Sans. The safety factors cover the widest common
# fallback, DejaVu Sans, measured against these tables on real card text:
# regular runs up to ~16% wider, bold up to ~25%, DejaVu Sans Mono ~0.3%.
