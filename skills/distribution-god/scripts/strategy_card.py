_EXTRA = {"·": 278, "–": 556, "—": 1000, "→": 1000, "×": 584, "≥": 549, "≤": 549,
          "…": 1000, "’": 222, "‘": 222, "“": 333, "”": 333, "€": 556, "£": 556}
SAFETY = {False: 1.17, True: 1.26, "mono": 1.03}  # keyed by bold / monospace


def text_width(s: str, size: float, bold: bool = False, spacing: float = 0.0,
               mono: bool = False) -> float:
    if mono:
        return len(s) * (0.6 * size + spacing)
    table = _BOLD if bold else _REG
    units = 0
    for ch in s:
        if ch in table:
            units += table[ch]
        elif ch in _EXTRA:
            units += _EXTRA[ch]
        elif ord(ch) >= 0x2E80:  # CJK and other full-width scripts
            units += 1000
        else:
            units += 611 if bold else 556
    return units * size / 1000 + spacing * len(s)


# Style name -> (font size, bold, letter-spacing, monospace). Mirrors the template CSS.
STYLES = {
    "kicker": (20, True, 2.4, False),
    "label": (19, True, 2.2, False),
    "conf": (16, True, 1.6, False),
    "h1": (56, True, -0.5, False),
    "sub": (25, False, 0, False),
    "sub-b": (25, True, 0, False),
    "band": (22, False, 0, False),
    "note": (19, False, 0, False),
    "note-c": (19, True, 0, False),
    "crux": (27, False, 0, False),
    "crux-b": (27, True, 0, False),
    "row": (22, False, 0, False),
    "body": (21, False, 0, False),
    "body-b": (21, True, 0, False),
    "mono": (21, False, 0, True),
    "fp": (18, False, 0, False),
    "fp-b": (18, True, 0, False),
}


def span_width(spans: list[tuple[str, str]], safe: bool = False) -> float:
    """Estimated rendered width; with safe=True, the worst case across fonts."""
    total = 0.0
    for style, text in spans:
        size, bold, spacing, mono = STYLES[style]
        factor = SAFETY["mono" if mono else bold] if safe else 1.0
        total += text_width(text, size, bold, spacing, mono) * factor
    return total


# --- Data -> slots ----------------------------------------------------------

class CardError(Exception):
    pass


def band_for(score: int, bands: list[tuple[int, str]]) -> str:
    for floor, label in bands:
        if score >= floor:
            return label
    raise AssertionError("unreachable")


def _int(value, name: str, lo: int, hi: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not lo <= value <= hi:
        raise CardError(f"{name} must be an integer {lo}–{hi}, got {value!r}")
    return value


def _str(value, name: str, allow_empty: bool = False) -> str:
    if not isinstance(value, str):
        raise CardError(f"{name} must be a string, got {type(value).__name__}")
    value = value.strip()
    if not value and not allow_empty:
        raise CardError(f"{name} is empty")
    if any(ord(c) < 32 for c in value):
        raise CardError(f"{name} contains a newline or control character")
    if "{{" in value or "}}" in value:
        raise CardError(f"{name} contains '{{{{' or '}}}}'")
    return value


def _dict(value, name: str) -> dict:
    if not isinstance(value, dict):
        raise CardError(f"{name} must be an object {{...}}, got {type(value).__name__}")
    return value


def _lines(value, name: str, n: int = 3) -> list[str]:
    if not isinstance(value, list) or len(value) != n:
        raise CardError(f"{name} must be a list of exactly {n} strings")
    return [_str(v, f"{name}[{i}]") for i, v in enumerate(value)]


def build_slots(data: dict) -> tuple[dict[str, str], list[tuple[str, list, float]]]:
    """Validate the card data. Returns (unescaped slot values, width checks)."""
    errors: list[str] = []
    data = _dict(data, "the card data")

    def guard(fn):
        try:
            return fn()
        except CardError as exc:
            errors.append(str(exc))
            return None

    product = guard(lambda: _str(data.get("product"), "product"))
    kicker = guard(lambda: _str(data.get("kicker"), "kicker"))
    date = guard(lambda: _str(data.get("date"), "date"))
    version = guard(lambda: _str(data.get("version"), "version"))
    tagline = guard(lambda: _lines(data.get("tagline"), "tagline", 2))
    crux = guard(lambda: _lines(data.get("crux"), "crux"))
    channel = guard(lambda: _lines(data.get("primary_channel"), "primary_channel"))
    kill = guard(lambda: _lines(data.get("kill_criteria"), "kill_criteria"))
    repo_url = guard(lambda: _str(data.get("repo_url"), "repo_url"))

    install = guard(lambda: _dict(data.get("install"), "install")) or {}
    prefix = guard(lambda: _str(install.get("prefix", "$"), "install.prefix"))
    command = guard(lambda: _str(install.get("command"), "install.command"))

    big = guard(lambda: _dict(data.get("bigness"), "bigness {score, confidence, note, breakdown}")) or {}
    big_n = guard(lambda: _int(big.get("score"), "bigness.score", 0, 25))
    confidence = big.get("confidence")
    if confidence not in ("High", "Medium", "Low"):
        errors.append(f"bigness.confidence must be High, Medium or Low, got {confidence!r}")
    big_note = guard(lambda: _str(big.get("note"), "bigness.note"))
    breakdown = big.get("breakdown")
    rows: list[tuple[str, int]] = []
    if not isinstance(breakdown, list) or len(breakdown) != 5:
        errors.append("bigness.breakdown must list all 5 rubric dimensions")
    else:
        for i, row in enumerate(breakdown):
            if not isinstance(row, dict):
                errors.append(f"bigness.breakdown[{i}] must be an object {{label, score}}")
                continue
            label = guard(lambda: _str(row.get("label"), f"bigness.breakdown[{i}].label"))
            score = guard(lambda: _int(row.get("score"), f"bigness.breakdown[{i}].score", 0, 5))
            if label is not None and score is not None:
                rows.append((label, score))
        labels = sorted(label for label, _ in rows)
        if len(rows) == 5 and labels != sorted(BIGNESS_DIMENSIONS):
            errors.append("bigness.breakdown labels must be exactly: " + ", ".join(BIGNESS_DIMENSIONS))
        if len(rows) == 5 and big_n is not None and sum(s for _, s in rows) != big_n:
            errors.append(f"bigness.breakdown sums to {sum(s for _, s in rows)}, "
                          f"but bigness.score is {big_n}")

    moat = guard(lambda: _dict(data.get("moat"), "moat {score, note}")) or {}
    moat_n = guard(lambda: _int(moat.get("score"), "moat.score", 0, 25))
    moat_note = guard(lambda: _str(moat.get("note"), "moat.note"))

    if errors:
        raise CardError("\n".join(errors))

    band = band_for(big_n, BIGNESS_BANDS)
    big_conf = "LOW · PROVISIONAL" if confidence == "Low" else f"{confidence.upper()} CONFIDENCE"
    moat_band = band_for(moat_n, MOAT_BANDS)
    rows.sort(key=lambda r: (-r[1], BIGNESS_DIMENSIONS.index(r[0])))

    slots = {
        "PRODUCT": product, "KICKER": kicker.upper(), "DATE": date, "VERSION": version,
        "TAGLINE_A": tagline[0], "TAGLINE_B": tagline[1],
        "BIG_N": str(big_n), "BIG_BAND": band, "BIG_CONF": big_conf, "BIG_NOTE": big_note,
        "BIG_W": str(round(430 * big_n / 25)),
        "MOAT_N": str(moat_n), "MOAT_BAND": moat_band, "MOAT_NOTE": moat_note,
        "MOAT_W": str(max(14, round(430 * moat_n / 25))),
        "CRUX_A": crux[0], "CRUX_B": crux[1], "CRUX_C": crux[2],
        "CH_A": channel[0], "CH_B": channel[1], "CH_C": channel[2],
        "KILL_A": kill[0], "KILL_B": kill[1], "KILL_C": kill[2],
        "INSTALL_PREFIX": prefix, "INSTALL": command, "REPO_URL": repo_url,
    }
    for i, (label, score) in enumerate(rows, start=1):
        slots[f"R{i}_LABEL"] = label
        slots[f"R{i}_N"] = str(score)
        slots[f"R{i}_W"] = str(round(560 * score / 5))

    footer = f"{FINGERPRINT} v{version} · {date}"
    # (name, spans, available width in px). Geometry mirrors the template.
    checks = [
        ("kicker line", [("kicker", f"STRATEGY REPORT · {slots['KICKER']}")], 1040),
        ("product", [("h1", product)], 1040),
        ("tagline[0]", [("sub", tagline[0])], 1040),
        ("tagline[1]", [("sub-b", tagline[1])], 1040),
        ("bigness band", [("band", band)], 454),
        ("bigness confidence", [("conf", big_conf)],
         554 - 116 - 16 - round(span_width([("label", "BIGNESS")], safe=True))),
        ("bigness.note", [("note", big_note)], 454),
        ("moat band", [("band", moat_band)], 454),
        ("moat.note", [("note-c", moat_note)], 454),
        ("crux[0]", [("crux", "The crux: "), ("crux-b", crux[0])], 1008),
        ("crux[1]", [("crux-b", crux[1])], 1008),
        ("crux[2]", [("crux", crux[2])], 1008),
        ("primary_channel[0]", [("body-b", channel[0])], 458),
        ("primary_channel[1]", [("body", channel[1])], 458),
        ("primary_channel[2]", [("body", channel[2])], 458),
        ("kill_criteria[0]", [("body-b", kill[0])], 454),
        ("kill_criteria[1]", [("body", kill[1])], 454),
        ("kill_criteria[2]", [("body", kill[2])], 454),
        ("install", [("mono", f"{prefix} {command}")], 1002),
        ("repo_url", [("fp-b", repo_url)], 1040 - 24 - round(span_width([("fp", footer)], safe=True))),
    ]
    checks += [(f"breakdown label {label!r}", [("row", label)], 290) for label, _ in rows]
    return slots, checks


def check_widths(checks) -> list[str]:
    problems = []
    for name, spans, avail in checks:
        est = span_width(spans, safe=True)
        if est > avail:
            text = "".join(t for _, t in spans)
            keep = max(1, int(len(text) * avail / est))
            problems.append(f"{name} is too wide (~{est:.0f}px of {avail}px): "
                            f"shorten to about {keep} characters — {text!r}")
    return problems


def xml_escape(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;")
             .replace(">", "&gt;").replace('"', "&quot;"))


def render_svg(data: dict) -> str:
    slots, checks = build_slots(data)
    problems = check_widths(checks)
    if problems:
        raise CardError("\n".join(problems))
    svg = TEMPLATE.read_text(encoding="utf-8")
    for key, value in slots.items():
        svg = svg.replace("{{" + key + "}}", xml_escape(value))
    if "{{" in svg or "}}" in svg:
        raise CardError("template slot left unfilled: " + svg[svg.find("{{"):svg.find("{{") + 30])
    validate_svg_text(svg)
    return svg


def validate_svg_text(svg: str) -> None:
    try:
        doc = xml.dom.minidom.parseString(svg.encode("utf-8"))
    except Exception as exc:  # expat raises several types
        raise CardError(f"output is not well-formed XML: {exc}") from exc
    if doc.documentElement.tagName != "svg":
        raise CardError("root element is not <svg>")
    if FINGERPRINT not in svg:
        raise CardError(f"fingerprint {FINGERPRINT!r} missing")


