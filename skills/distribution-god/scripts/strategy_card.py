#!/usr/bin/env python3
"""Render the distribution-god strategy card (SVG) from a JSON data file.

The model never hand-edits SVG: it writes plain values to a JSON file and this
script does everything that is easy to get wrong by hand — XML escaping, meter
widths, breakdown ordering, band labels derived from the rubric, per-line width
budgets (SVG text does not wrap), and a final parse of the output.

Usage:
  python3 strategy_card.py render CARD.json [--out assets/strategy-card.svg] [--force]
  python3 strategy_card.py check assets/strategy-card.svg
  python3 strategy_card.py example            # print a complete example CARD.json
  python3 strategy_card.py png assets/strategy-card.svg [--out assets/strategy-card.png]

Exit status: 0 on success, 1 on any validation error (nothing is written).
Standard library only; Python 3.8+.
"""

