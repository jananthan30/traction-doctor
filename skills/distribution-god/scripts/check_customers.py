#!/usr/bin/env python3
"""Lint a distribution-god FIRST-CUSTOMERS.md, the private outreach file.

Checks that the file is complete, honest, and safe to act on:
  - the title, the fingerprint (version, run date, web research on/off),
    and the private-file notice
  - every section present, in order, non-empty, with no unfilled slots
  - no email addresses, mailto: links or phone numbers anywhere
  - web runs: at most 12 openings, each linking exactly one public post, with
    the post date and the fetch date (YYYY-MM-DD; fetched on the run date or
    the day after; posted no later than fetched and at most a year before),
    the person's words in quotes (15 words at most), why it fits, and where
    to reply; no URL listed twice; fewer than 3 openings must be stated as
    "only N openings found"
  - local-only runs: Openings says NOT RESEARCHED and the file links no
    individual post
  - at least two message drafts, each 150 words at most and each disclosing
    that the sender built the product
  - the tracker lists every opening, and the rules keep "One message per
    person"
  - when called from check_report.py: the version, date and web flag match
    the report's dg line

Usage:
  python3 check_customers.py FIRST-CUSTOMERS.md [more files...]

Exit status: 0 when every file passes, 1 otherwise. Standard library only.
"""

from __future__ import annotations

import datetime as dt
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_report import LINK, section, tables, unfilled_slots  # noqa: E402

SECTIONS = [
    r"## Who you're looking for",
    r"## The offer",
    r"## Where they are",
    r"## Openings",
    r"## Message drafts",
    r"## First 14 days",
    r"## Tracker",
    r"## Rules",
]
MAX_OPENINGS = 12
MAX_QUOTE_WORDS = 15
MAX_DRAFT_WORDS = 150
HEADER = re.compile(r"Generated by distribution-god v(\d+\.\d+\.\d+) on (\d{4}-\d{2}-\d{2}) "
                    r"\(web research (on|off)\)")
EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}\b")
# Narrow on purpose: ISO dates, star counts, versions and SHAs must not match.
PHONE = re.compile(r"\+\d{1,3}[ .-]?\(?\d{1,4}\)?[ .-]?\d{3,4}[ .-]?\d{3,4}\b"
                   r"|\(\d{3}\)\s?\d{3}[ .-]\d{4}\b"
                   r"|\b\d{3}[.-]\d{3}[.-]\d{4}\b")
# Links to one person's post. They belong only in FIRST-CUSTOMERS.md, which
# stays private; the report (often committed) names venues, never people.
POST_URL = re.compile(
    r"reddit\.com/r/[^/\s)]+/comments/"
    r"|news\.ycombinator\.com/item\?id="
    r"|github\.com/[^/\s)]+/[^/\s)]+/(?:issues|discussions|pull)/\d+"
    r"|(?:stackoverflow|serverfault|superuser|askubuntu)\.com/(?:questions|q|a)/\d+"
    r"|[\w-]+\.stackexchange\.com/(?:questions|q|a)/\d+"
    r"|(?:x|twitter)\.com/[^/\s)]+/status/\d+"
    r"|linkedin\.com/(?:posts|feed/update)/"
    r"|indiehackers\.com/post/"
    r"|lobste\.rs/s/")
DISCLOSURE = re.compile(r"\bI\s+(?:built|made|wrote|created|maintain)\b"
                        r"|\bI(?:'|’)?m\s+the\s+(?:author|maintainer|creator|developer|builder)\b"
                        r"|\bI\s+am\s+the\s+(?:author|maintainer|creator|developer|builder)\b", re.I)
QUOTE = re.compile(r"[\"“]([^\"”]+)[\"”]")
ISO = re.compile(r"\d{4}-\d{2}-\d{2}")


def _date(s: str) -> dt.date | None:
    m = ISO.fullmatch(s.strip().strip("*`"))
    if not m:
        return None
    try:
        return dt.date.fromisoformat(m.group(0))
    except ValueError:
        return None


def _col(header: list[str], prefix: str) -> int | None:
    return next((i for i, c in enumerate(header) if c.startswith(prefix)), None)


def _urls(cell: str) -> list[str]:
    return re.findall(r"\]\((https?://[^)\s]+)\)|<(https?://[^>\s]+)>", cell)


def check_text(text: str, dg: dict | None = None) -> tuple[list[str], list[str]]:
    """Problems with a FIRST-CUSTOMERS.md's text. `dg` is the linking report's
    dg line, when there is one; the file must then agree with it."""
    errors: list[str] = []
    warnings: list[str] = []

    if not re.match(r"# First customers — \S", text):
        errors.append("first line must be '# First customers — <product name>'")
    head = HEADER.search(text)
    if not head:
        errors.append("missing the fingerprint 'Generated by distribution-god v<version> on "
                      "<YYYY-MM-DD> (web research on|off)'")
    if "Private working file" not in text:
        errors.append("missing the private-file notice ('**Private working file.** …')")
    version, run_date, web = (head.group(1), _date(head.group(2)), head.group(3) == "on") if head \
        else (None, None, True)
    if head and dg is not None:
        if version != str(dg.get("v")) or head.group(2) != str(dg.get("date")):
            errors.append(f"stamped v{version} · {head.group(2)} but the report is "
                          f"v{dg.get('v')} · {dg.get('date')} — regenerate it with the report")
        if isinstance(dg.get("web"), bool) and web != dg["web"]:
            errors.append(f"says web research {head.group(3)} but the report's dg.web is "
                          f"{str(dg['web']).lower()}")

    pos = -1
    for heading in SECTIONS:
        m = re.search(rf"^{heading}\s*$", text, re.M)
        name = heading.replace("\\", "")
        if not m:
            errors.append(f"missing section: {name}")
        elif m.start() < pos:
            errors.append(f"section out of order: {name}")
        else:
            pos = m.start()
            if not section(text, heading).strip():
                errors.append(f"section is empty: {name}")
    errors.extend(unfilled_slots(text))

    for m in EMAIL.finditer(text):
        errors.append(f"email address {m.group(0)!r}: never record contact details — reply where "
                      "they posted")
    if re.search(r"mailto:", text, re.I):
        errors.append("mailto: link: never record contact details — reply where they posted")
    for m in PHONE.finditer(text):
        errors.append(f"phone number {m.group(0)!r}: never record contact details")

    openings = section(text, r"## Openings")
    opening_urls: list[str] = []
    if not web:
        if "NOT RESEARCHED" not in openings:
            errors.append("a local-only file's Openings must say 'NOT RESEARCHED — re-run with web "
                          "access'")
        for m in POST_URL.finditer(text):
            errors.append(f"a local-only run found no one, so it links no post: {m.group(0)!r}")
    else:
        if "NOT RESEARCHED" in openings:
            errors.append("Openings says NOT RESEARCHED but web research was on — write 'only N "
                          "openings found' instead")
        found = [t for t in tables(openings) if t and _col([c.lower() for c in t[0]], "their words")
                 is not None]
        rows = found[0][1:] if found else []
        if not found and not re.search(r"\bno openings found\b", openings, re.I):
            errors.append("Openings needs its table (#, Opening, Posted, Fetched, Their words, "
                          "Why it fits, Reply via) or 'no openings found'")
        if found:
            header = [c.replace("*", "").strip().lower() for c in found[0][0]]
            idx = {k: _col(header, k) for k in ("opening", "posted", "fetched", "their words",
                                                "why it fits", "reply via")}
            missing = [k for k, v in idx.items() if v is None]
            if missing:
                errors.append(f"the Openings table is missing columns: {', '.join(missing)}")
                rows = []
            if len(rows) > MAX_OPENINGS:
                errors.append(f"{len(rows)} openings: keep the best {MAX_OPENINGS} or fewer")
            for r in rows:
                num = r[0].strip()
                cell = lambda k: r[idx[k]].strip() if idx[k] < len(r) else ""  # noqa: E731
                urls = [a or b for a, b in _urls(cell("opening"))]
                if len(urls) != 1:
                    errors.append(f"opening {num}: link exactly one public post (found {len(urls)})")
                else:
                    opening_urls.append(urls[0])
                posted, fetched = _date(cell("posted")), _date(cell("fetched"))
                if posted is None or fetched is None:
                    errors.append(f"opening {num}: Posted and Fetched must be dates (YYYY-MM-DD)")
                else:
                    if posted > fetched:
                        errors.append(f"opening {num}: posted {posted} is after it was fetched")
                    elif (fetched - posted).days > 365:
                        errors.append(f"opening {num}: posted {posted}, over a year before it was "
                                      "fetched — too old to reply to")
                    if run_date and not 0 <= (fetched - run_date).days <= 1:
                        errors.append(f"opening {num}: fetched {fetched}, not during this run "
                                      f"({run_date}) — re-fetch it or drop it")
                words = QUOTE.search(cell("their words"))
                if not words:
                    errors.append(f"opening {num}: give their words in quotes")
                elif len(words.group(1).split()) > MAX_QUOTE_WORDS:
                    errors.append(f"opening {num}: quote at most {MAX_QUOTE_WORDS} words "
                                  f"(found {len(words.group(1).split())})")
                for k in ("why it fits", "reply via"):
                    if not cell(k):
                        errors.append(f"opening {num}: '{k}' is empty")
            dupes = sorted({u for u in opening_urls if opening_urls.count(u) > 1})
            for u in dupes:
                errors.append(f"opening listed twice: {u}")
        if len(rows) < 3 and not re.search(r"\b(?:only \d+ openings? found|no openings found)\b",
                                           openings, re.I):
            errors.append(f"{len(rows)} opening(s): say 'only {len(rows)} openings found' and what "
                          "that says about the wedge")

    drafts = section(text, r"## Message drafts")
    blocks = [b for b in re.split(r"^### .*$", drafts, flags=re.M)[1:]]
    quoted = []
    for b in blocks:
        q = "\n".join(line.lstrip()[1:].strip() for line in b.splitlines()
                      if line.lstrip().startswith(">"))
        if q.strip():
            quoted.append(q)
    if len(quoted) < 2:
        errors.append("Message drafts needs at least two drafts, each under a '### <channel>' "
                      "heading as a '>' quote")
    for i, q in enumerate(quoted, 1):
        if not DISCLOSURE.search(q):
            errors.append(f"draft {i} must disclose that you built it ('I built …', "
                          "'I maintain …')")
        n = len(q.split())
        if n > MAX_DRAFT_WORDS:
            errors.append(f"draft {i} is {n} words; keep it under {MAX_DRAFT_WORDS}")

    tracker = section(text, r"## Tracker")
    tracked = [t for t in tables(tracker) if t and _col([c.replace("*", "").strip().lower()
                                                         for c in t[0]], "sent") is not None]
    if not tracked:
        errors.append("Tracker needs its table (#, Opening, Sent, Reply, Tried it, Outcome, Next)")
    else:
        listed = {u for row in tracked[0][1:] for cell in row for a, b in _urls(cell) for u in (a or b,)}
        for u in opening_urls:
            if u not in listed:
                errors.append(f"the tracker is missing the opening {u}")
    if not re.search(r"one message per person", section(text, r"## Rules"), re.I):
        errors.append("Rules must keep 'One message per person' — no follow-ups")
    return errors, warnings


def check(path: Path, dg: dict | None = None) -> tuple[list[str], list[str]]:
    return check_text(path.read_text(encoding="utf-8"), dg)


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__.strip().split("\n\n")[2], file=sys.stderr)
        return 2
    failed = False
    for arg in argv:
        path = Path(arg)
        if not path.exists():
            print(f"{arg}: not found", file=sys.stderr)
            failed = True
            continue
        errors, warnings = check(path)
        for w in warnings:
            print(f"{arg}: warning: {w}")
        if errors:
            failed = True
            print(f"{arg}: {len(errors)} problem(s)")
            for e in errors:
                print(f"  - {e}")
        else:
            print(f"{arg}: ok")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
