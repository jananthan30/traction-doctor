"""Unit tests for the close-gaps skill: check_ideas.py and its references.

Run: python3 -m unittest discover -s tests
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = ROOT / "skills" / "close-gaps"
SCRIPT = SKILL_DIR / "scripts" / "check_ideas.py"
FIXTURE = ROOT / "tests" / "fixtures" / "sample-ideas"
sys.path.insert(0, str(SKILL_DIR / "scripts"))

import check_ideas  # noqa: E402

I4_ROW = "| I4 | Public deploy benchmark | `moat.brand` | proven | publish one benchmark page | L | 13/20 |\n"
I4_TOP = ',{"id":"I4","score":13,"kind":"proven","build":"L"}'


def offline(text: str) -> str:
    """The fixture as a local-only run: web off, every Weakness section marked."""
    text = text.replace('"web":true', '"web":false')
    return re.sub(r"(^## Weakness \d+:.*\n)", r"\1\nNOT RESEARCHED — re-run with web access\n",
                  text, flags=re.M)


class CheckIdeasTestCase(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        shutil.copytree(FIXTURE, self.tmp, dirs_exist_ok=True)
        self.path = self.tmp / "CLOSE-GAPS.md"
        self.text = self.path.read_text()

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def errors_for(self, text: str) -> list[str]:
        self.path.write_text(text)
        return check_ideas.check(self.path)[0]

    def errors_after(self, old: str, new: str, count: int = 1) -> list[str]:
        self.assertIn(old, self.text, "fixture changed; update the test")
        return self.errors_for(self.text.replace(old, new, count))

    def assertCaught(self, errors: list[str], pattern: str):
        self.assertTrue(any(re.search(pattern, e) for e in errors),
                        f"expected an error matching {pattern!r}, got {errors}")


class StructureTests(CheckIdeasTestCase):
    def test_valid_fixture_passes(self):
        errors, warnings = check_ideas.check(self.path)
        self.assertEqual(errors, [])
        self.assertEqual(warnings, [])

    def test_title_required(self):
        self.assertCaught(self.errors_after("# Closing the gaps — acme-cli", "# Ideas for acme-cli"),
                          "first line must be")

    def test_cg_line_required(self):
        self.assertCaught(self.errors_after("<!-- cg: ", "<!-- xx: "), r"missing the '<!-- cg:")

    def test_cg_line_must_be_json(self):
        self.assertCaught(self.errors_after('"web":true,', '"web":tru,'), "cg line is not valid JSON")

    def test_cg_keys_required(self):
        self.assertCaught(self.errors_after('"mode":"sequential",', ""), "cg line missing key 'mode'")

    def test_target_ids_are_checked(self):
        self.assertCaught(self.errors_after('"targets":["crux",', '"targets":["moat.vibes",'),
                          "invalid target id 'moat.vibes'")

    def test_fingerprint_must_match_version(self):
        errors = self.errors_after("Generated by distribution-god v0.3.0 (close-gaps)",
                                   "Generated by distribution-god v0.2.0 (close-gaps)")
        self.assertCaught(errors, r"fingerprint 'Generated by distribution-god v0\.3\.0")

    def test_missing_section(self):
        self.assertCaught(self.errors_after("## Shiny but not now", "## Later"),
                          "missing section: ## Shiny but not now")

    def test_section_out_of_order(self):
        text = (self.text.replace("## Dissent", "## @@").replace("## Sources", "## Dissent")
                .replace("## @@", "## Sources"))
        self.assertCaught(self.errors_for(text), "section out of order: ## Sources")

    def test_weakness_sections_follow_targets(self):
        errors = self.errors_after('"targets":["crux","bigness.delivery","moat.brand"]',
                                   '"targets":["bigness.delivery","crux","moat.brand"]')
        self.assertCaught(errors, r"Weakness 1 is `crux` but cg\.targets\[0\] is `bigness\.delivery`")

    def test_weakness_sections_are_numbered(self):
        self.assertCaught(self.errors_after("## Weakness 3:", "## Weakness 4:"), "numbered 1, 2, 3")

    def test_one_weakness_section_per_target(self):
        errors = self.errors_after('"targets":["crux","bigness.delivery","moat.brand"]',
                                   '"targets":["crux","bigness.delivery"]')
        self.assertCaught(errors, r"lists 2 target\(s\) but there are 3 Weakness sections")

    def test_curly_apostrophe_heading_is_accepted(self):
        self.assertEqual(self.errors_after("## Can't move now", "## Can’t move now"), [])

    def test_unfilled_slot(self):
        errors = self.errors_after("**Why this one:** brand is the report's only buildable power.",
                                   "**Why this one:** <band arithmetic>")
        self.assertCaught(errors, "unfilled slot '<band arithmetic>'")

    def test_pragmatist_record(self):
        self.assertCaught(self.errors_after("**Pragmatist adjustments:**", "**Adjustments:**"),
                          "Pragmatist adjustments")

    def test_web_run_sources_need_links(self):
        text = self.text[:self.text.index("## Sources")] + "## Sources\n\n- none\n"
        self.assertCaught(self.errors_for(text), "Sources section needs at least one link")

    def test_web_run_may_not_say_not_researched(self):
        errors = self.errors_after("**Why this one:** brand is the report's only buildable power.",
                                   "NOT RESEARCHED — re-run with web access\n\n"
                                   "**Why this one:** brand is the report's only buildable power.")
        self.assertCaught(errors, "says 'NOT RESEARCHED' but cg.web is true")

    def test_local_only_run_needs_markers(self):
        self.assertCaught(self.errors_after('"web":true', '"web":false'),
                          "cg.web is false but Weakness 1 does not say 'NOT RESEARCHED'")

    def test_line_budget_is_a_warning(self):
        self.path.write_text(self.text + "- filler\n" * 300)
        errors, warnings = check_ideas.check(self.path)
        self.assertEqual(errors, [])
        self.assertTrue(any("lines" in w for w in warnings), warnings)

    def test_cli_prints_ok_and_problems(self):
        ok = subprocess.run([sys.executable, str(SCRIPT), str(self.path)], capture_output=True, text=True)
        self.assertEqual(ok.returncode, 0, ok.stdout + ok.stderr)
        self.assertIn("CLOSE-GAPS.md: ok", ok.stdout)
        self.path.write_text(self.text.replace("<!-- cg: ", "<!-- xx: "))
        bad = subprocess.run([sys.executable, str(SCRIPT), str(self.path)], capture_output=True, text=True)
        self.assertEqual(bad.returncode, 1)
        self.assertIn("problem(s)", bad.stdout)

    def test_missing_sibling_skill_is_a_clear_error(self):
        lone = self.tmp / "skills" / "close-gaps" / "scripts"
        lone.mkdir(parents=True)
        shutil.copy(SCRIPT, lone)
        run = subprocess.run([sys.executable, str(lone / "check_ideas.py"), str(self.path)],
                             capture_output=True, text=True)
        self.assertNotEqual(run.returncode, 0)
        self.assertIn("needs the distribution-god skill", run.stderr)
        self.assertNotIn("Traceback", run.stderr)


if __name__ == "__main__":
    unittest.main()
