class StrategyCardTests(unittest.TestCase):
    def setUp(self):
        self.data = copy.deepcopy(strategy_card.EXAMPLE)

    def test_example_renders_valid_svg(self):
        svg = strategy_card.render_svg(self.data)
        xml.dom.minidom.parseString(svg.encode())
        self.assertNotIn("{{", svg)
        self.assertIn(f"Generated by traction-doctor v{VERSION}", svg)

    def test_special_characters_are_escaped(self):
        self.data["product"] = 'R&D <tools> "x"'
        svg = strategy_card.render_svg(self.data)
        xml.dom.minidom.parseString(svg.encode())
        self.assertIn("R&amp;D &lt;tools&gt; &quot;x&quot;", svg)

    def test_breakdown_must_sum_to_score(self):
        self.data["bigness"]["score"] = 13
        with self.assertRaisesRegex(strategy_card.CardError, "sums to 12"):
            strategy_card.render_svg(self.data)

    def test_breakdown_labels_must_match_rubric(self):
        self.data["bigness"]["breakdown"][0]["label"] = "TAM"
        with self.assertRaisesRegex(strategy_card.CardError, "labels must be exactly"):
            strategy_card.render_svg(self.data)

    def test_overflow_is_rejected_with_guidance(self):
        self.data["moat"]["note"] = "An extremely long moat note that cannot possibly fit"
        with self.assertRaisesRegex(strategy_card.CardError, r"moat\.note is too wide.*shorten"):
            strategy_card.render_svg(self.data)

    def test_bands_come_from_the_rubric(self):
        self.assertEqual(strategy_card.band_for(12, strategy_card.BIGNESS_BANDS),
                         "Niche tool / lifestyle business")
        self.assertEqual(strategy_card.band_for(14, strategy_card.BIGNESS_BANDS),
                         "Strong business possible")
        self.assertEqual(strategy_card.band_for(4, strategy_card.MOAT_BANDS), "Nothing defensible yet")
        self.data["bigness"]["confidence"] = "Low"
        self.assertIn("LOW · PROVISIONAL", strategy_card.render_svg(self.data))

    def test_rubric_file_uses_the_same_band_labels(self):
        rubric = (ROOT / "skills/traction-doctor/references/scoring-rubrics.md").read_text()
        for _, label in strategy_card.BIGNESS_BANDS + strategy_card.MOAT_BANDS:
            self.assertIn(label, rubric)
        for dim in strategy_card.BIGNESS_DIMENSIONS:
            self.assertIn(f"**{dim}**", rubric)

    def test_render_refuses_foreign_svg(self):
        with tempfile.TemporaryDirectory() as tmp:
            data = Path(tmp, "card.json")
            data.write_text(json.dumps(self.data))
            out = Path(tmp, "strategy-card.svg")
            out.write_text("<svg xmlns='http://www.w3.org/2000/svg'/>")
            cmd = [sys.executable, str(SCRIPTS / "strategy_card.py"), "render", str(data), "--out", str(out)]
            refused = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(refused.returncode, 1)
            self.assertIn("not generated by traction-doctor", refused.stderr)
            forced = subprocess.run(cmd + ["--force"], capture_output=True, text=True)
            self.assertEqual(forced.returncode, 0, forced.stderr)
            again = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(again.returncode, 0, "re-rendering our own card must not need --force")

    def test_render_overwrites_a_card_from_before_the_rename(self):
        with tempfile.TemporaryDirectory() as tmp:
            data = Path(tmp, "card.json")
            data.write_text(json.dumps(self.data))
            out = Path(tmp, "strategy-card.svg")
            out.write_text(strategy_card.render_svg({**self.data, "version": "0.4.0"}))
            self.assertIn("Generated by distribution-god v0.4.0", out.read_text())
            cmd = [sys.executable, str(SCRIPTS / "strategy_card.py"), "render", str(data), "--out", str(out)]
            run = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(run.returncode, 0, run.stderr)
            self.assertIn(f"Generated by traction-doctor v{VERSION}", out.read_text())

    def test_the_name_follows_the_version(self):
        self.assertEqual(strategy_card.tool_for("0.4.9"), "distribution-god")
        self.assertEqual(strategy_card.tool_for("0.5.0"), "traction-doctor")
        self.assertEqual(strategy_card.tool_for("1.0.0"), "traction-doctor")
        self.assertEqual(strategy_card.tool_for("dev"), "traction-doctor")


