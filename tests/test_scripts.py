class ReleaseMetadataTests(unittest.TestCase):
    def test_versions_agree(self):
        version = json.loads((ROOT / ".claude-plugin/plugin.json").read_text())["version"]
        skill = (ROOT / "skills/traction-doctor/SKILL.md").read_text()
        self.assertIn(f"traction-doctor **v{version}**", skill)
        self.assertRegex(skill, rf"Use exactly\s+`{re.escape(version)}`")
        close_gaps = (ROOT / "skills/close-gaps/SKILL.md").read_text()
        self.assertIn(f"traction-doctor **v{version}**", close_gaps)
        self.assertRegex(close_gaps, rf"Use exactly\s+`{re.escape(version)}`")
        changelog = (ROOT / "CHANGELOG.md").read_text()
        first = re.search(r"^## \[?(\d+\.\d+\.\d+)", changelog, re.M)
        self.assertIsNotNone(first, "CHANGELOG.md has no version heading")
        self.assertEqual(first.group(1), version, "top CHANGELOG entry must match plugin.json")
        self.assertEqual(strategy_card.EXAMPLE["version"], version)
        self.assertIn(f"Current version: {version}.", (ROOT / "llms.txt").read_text())
        self.assertIn(f"(traction-doctor v{version})",
                      (ROOT / "skills/traction-doctor/references/scoring-rubrics.md").read_text())
        marketplace = json.loads((ROOT / ".claude-plugin/marketplace.json").read_text())
        for plugin in marketplace["plugins"]:
            if "version" in plugin:
                self.assertEqual(plugin["version"], version)

    def test_marketplace_moves_installs_of_the_old_name(self):
        plugin = json.loads((ROOT / ".claude-plugin/plugin.json").read_text())
        marketplace = json.loads((ROOT / ".claude-plugin/marketplace.json").read_text())
        self.assertEqual(plugin["name"], strategy_card.TOOL)
        self.assertEqual(marketplace["name"], strategy_card.TOOL)
        self.assertEqual([p["name"] for p in marketplace["plugins"]], [strategy_card.TOOL])
        self.assertEqual(marketplace["renames"], {strategy_card.FORMER_TOOL: strategy_card.TOOL})

    def test_agents_point_at_existing_sensor_methods(self):
        for agent in (ROOT / "agents").glob("*.md"):
            for ref in re.findall(r"\$\{CLAUDE_PLUGIN_ROOT\}/(\S+?\.md)", agent.read_text()):
                self.assertTrue((ROOT / ref).exists(), f"{agent.name} points at missing {ref}")

    def test_skill_references_exist(self):
        # Files the skill reads from its own directory. `assets/strategy-card.svg`
        # is an output path in the analyzed repo, so only templates count here.
        skill_dir = ROOT / "skills/traction-doctor"
        texts = [p.read_text() for p in [skill_dir / "SKILL.md", *skill_dir.glob("references/*.md")]]
        refs = set(re.findall(r"((?:references|scripts)/[\w./-]+\.(?:md|py)|assets/[\w.-]+\.template\.svg)",
                              "\n".join(texts)))
        self.assertTrue(refs)
        for ref in refs:
            self.assertTrue((skill_dir / ref).exists(), f"skill references missing {ref}")


if __name__ == "__main__":
    unittest.main()
