class StrategyCardTests(unittest.TestCase):
    def setUp(self):
        self.data = copy.deepcopy(strategy_card.EXAMPLE)

    def test_example_renders_valid_svg(self):
        svg = strategy_card.render_svg(self.data)
        xml.dom.minidom.parseString(svg.encode())
        self.assertNotIn("{{", svg)
        self.assertIn(f"Generated by distribution-god v{VERSION}", svg)

    def test_special_characters_are_escaped(self):
        self.data["product"] = 'R&D <tools> "x"'
        svg = strategy_card.render_svg(self.data)
        xml.dom.minidom.parseString(svg.encode())
        self.assertIn("R&amp;D &lt;tools&gt; &quot;x&quot;", svg)

    def test_breakdown_must_sum_to_score(self):
        self.data["bigness"]["score"] = 13
        with self.assertRaisesRegex(strategy_card.CardError, "sums to 12"):
            strategy_card.render_svg(self.data)

    def test_breakdown_labels_must_match_rubric(self):
        self.data["bigness"]["breakdown"][0]["label"] = "TAM"
        with self.assertRaisesRegex(strategy_card.CardError, "labels must be exactly"):
            strategy_card.render_svg(self.data)

    def test_overflow_is_rejected_with_guidance(self):
        self.data["moat"]["note"] = "An extremely long moat note that cannot possibly fit"
        with self.assertRaisesRegex(strategy_card.CardError, r"moat\.note is too wide.*shorten"):
            strategy_card.render_svg(self.data)

    def test_bands_come_from_the_rubric(self):
        self.assertEqual(strategy_card.band_for(12, strategy_card.BIGNESS_BANDS),
                         "Niche tool / lifestyle business")
        self.assertEqual(strategy_card.band_for(14, strategy_card.BIGNESS_BANDS),
                         "Strong business possible")
        self.assertEqual(strategy_card.band_for(4, strategy_card.MOAT_BANDS), "Nothing defensible yet")
        self.data["bigness"]["confidence"] = "Low"
        self.assertIn("LOW · PROVISIONAL", strategy_card.render_svg(self.data))

    def test_rubric_file_uses_the_same_band_labels(self):
        rubric = (ROOT / "skills/distribution-god/references/scoring-rubrics.md").read_text()
        for _, label in strategy_card.BIGNESS_BANDS + strategy_card.MOAT_BANDS:
            self.assertIn(label, rubric)
        for dim in strategy_card.BIGNESS_DIMENSIONS:
            self.assertIn(f"**{dim}**", rubric)

    def test_render_refuses_foreign_svg(self):
        with tempfile.TemporaryDirectory() as tmp:
            data = Path(tmp, "card.json")
            data.write_text(json.dumps(self.data))
            out = Path(tmp, "strategy-card.svg")
            out.write_text("<svg xmlns='http://www.w3.org/2000/svg'/>")
            cmd = [sys.executable, str(SCRIPTS / "strategy_card.py"), "render", str(data), "--out", str(out)]
            refused = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(refused.returncode, 1)
            self.assertIn("not generated by distribution-god", refused.stderr)
            forced = subprocess.run(cmd + ["--force"], capture_output=True, text=True)
            self.assertEqual(forced.returncode, 0, forced.stderr)
            again = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(again.returncode, 0, "re-rendering our own card must not need --force")


class CheckReportTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        shutil.copytree(FIXTURE, self.tmp, dirs_exist_ok=True)
        self.report = self.tmp / "STRATEGY.md"
        self.text = self.report.read_text()

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def errors_after(self, old: str, new: str, count: int = 1) -> list[str]:
        self.assertIn(old, self.text, "fixture changed; update the test")
        self.report.write_text(self.text.replace(old, new, count))
        return check_report.check(self.report)[0]

    def assertCaught(self, errors: list[str], pattern: str):
        self.assertTrue(any(re.search(pattern, e) for e in errors),
                        f"expected an error matching {pattern!r}, got {errors}")

    def test_valid_fixture_passes(self):
        errors, _ = check_report.check(self.report)
        self.assertEqual(errors, [])

    def test_missing_section(self):
        self.assertCaught(self.errors_after("## 9. Kill criteria", "## Kill"), "missing section: ## 9")

    def test_dg_disagrees_with_headline(self):
        self.assertCaught(self.errors_after('"bigness":12', '"bigness":13'), "subs sum to 12")

    def test_headline_disagrees_with_breakdown(self):
        errors = self.errors_after("| Market headroom | 2/5 |", "| Market headroom | 3/5 |")
        self.assertCaught(errors, "market shows 3 but dg.subs.market is 2")

    def test_wrong_band_label(self):
        errors = self.errors_after("Niche tool / lifestyle business (confidence",
                                   "Strong business possible (confidence")
        self.assertCaught(errors, "must name the band 'Niche tool / lifestyle business'")

    def test_low_confidence_needs_provisional(self):
        errors = self.errors_after('"confidence":"Medium"', '"confidence":"Low"')
        self.assertCaught(errors, "PROVISIONAL")

    def test_unfilled_slot(self):
        self.assertCaught(self.errors_after("- **Category:** developer deploy tooling",
                                            "- **Category:** <name it>"), "unfilled slot '<name it>'")

    def test_market_dollar_figure_needs_estimate(self):
        errors = self.errors_after("- **Timing risk:** hosting platforms bundle one-command deploys",
                                   "- **Timing risk:** a $2B incumbent bundles deploys")
        self.assertCaught(errors, "market figure without ESTIMATE")

    def test_rival_needs_source(self):
        self.assertCaught(self.errors_after("[site](https://example.com/rival)", "their site"),
                          "has no source link")

    def test_exactly_one_primary(self):
        self.assertCaught(self.errors_after("| 12/20 | secondary |", "| 12/20 | PRIMARY |"),
                          "exactly one PRIMARY")

    def test_five_actions(self):
        self.assertCaught(self.errors_after("5. Publish one benchmark", "Publish one benchmark"),
                          "exactly 5 numbered actions")

    def test_red_team_record(self):
        self.assertCaught(self.errors_after("**Red-team adjustments:**", "**Adjustments:**"),
                          "Red-team adjustments")

    def test_no_web_must_say_not_researched(self):
        self.assertCaught(self.errors_after('"web":true', '"web":false'), "NOT RESEARCHED")

    def test_card_must_exist_and_parse(self):
        (self.tmp / "assets" / "strategy-card.svg").write_text("<svg><text>R&D</text></svg>")
        errors = check_report.check(self.report)[0]
        self.assertCaught(errors, "not well-formed XML")

    def test_dg_line_json_containing_braces_is_not_a_slot(self):
        errors, _ = check_report.check(self.report)
        self.assertFalse(any("{{" in e for e in errors))

    def test_rubric_version_required(self):
        self.assertCaught(self.errors_after('"rubric":2,', ""), "missing key 'rubric'")

    def test_market_arithmetic_must_add_up(self):
        errors = self.errors_after("× $300–1,200/yr = $120M–$480M", "× $300–1,200/yr = $150M–$480M")
        self.assertCaught(errors, "doesn't add up.*works out to 120M–480M")

    def test_market_arithmetic_in_inline_code_is_checked(self):
        errors = self.errors_after("400k teams × $300–1,200/yr = $120M–$480M", "`400k × $300 = $150M`")
        self.assertCaught(errors, "doesn't add up")

    def test_arithmetic_with_division_and_ranges(self):
        ok = "36.5M × 1–3% ÷ 8 × $1,200–$2,400 = $54.75M–$328.5M"
        self.assertEqual(check_report.arithmetic_errors(ok), [])
        self.assertEqual(check_report.arithmetic_errors("150–300k × $240–480/yr = $36M–$144M"), [])
        self.assertTrue(check_report.arithmetic_errors("150–300k × $240–480/yr = $50M–$250M"))

    def test_nested_size_inputs_inherit_the_estimate_label(self):
        errors = self.errors_after(
            "- **Size:** ESTIMATE $120M–$480M SAM (geometric midpoint $240M): "
            "400k teams × $300–1,200/yr = $120M–$480M",
            "- **Size:** ESTIMATE $120M–$480M SAM (geometric midpoint $240M)\n"
            "  - Price: $300–1,200/yr per team\n  - 400k × $300–1,200 = $120M–$480M")
        self.assertEqual(errors, [])

    def test_size_headline_must_come_from_a_calculation(self):
        errors = self.errors_after("ESTIMATE $120M–$480M SAM", "ESTIMATE $150M–$480M SAM")
        self.assertCaught(errors, "Size headline 150M–480M doesn't match")

    def test_stated_midpoint_must_be_geometric(self):
        self.assertCaught(self.errors_after("(geometric midpoint $240M)", "(geometric midpoint $300M)"),
                          r"geometric midpoint 300M ≠ √\(low × high\) = 240M")

    def test_headroom_score_must_match_dollar_band(self):
        errors = self.errors_after('"market":2,"why_now":3', '"market":3,"why_now":2')
        self.assertCaught(errors, "Market headroom is scored 3 but .* falls in band 2")

    def test_money_in_plain_paragraphs_and_tables_is_checked(self):
        errors = self.errors_after("## 2. Market\n\n", "## 2. Market\n\nThe category is worth $5B a year.\n\n")
        self.assertCaught(errors, "market figure without")

    def test_capitalized_unverified_counts(self):
        errors = self.errors_after("- **Timing risk:** hosting platforms bundle one-command deploys",
                                   "- **Timing risk:** Unverified: a $2B incumbent bundles deploys")
        self.assertEqual(errors, [])

    def test_email_autolinks_are_not_slots(self):
        self.assertEqual(self.errors_after("- Rivals: [ExampleDeploy](https://example.com/rival)",
                                           "- Rivals: <founder@example.com>"), [])

    def test_extra_table_after_rivals_is_ignored(self):
        errors = self.errors_after("**Indirect:**", "| Feature | Us | Them |\n|---|---|---|\n"
                                   "| Offline | yes | no |\n\n**Indirect:**")
        self.assertEqual(errors, [])

    def test_zero_rivals_needs_no_padding(self):
        start = self.text.index("| Rival |")
        end = self.text.index("**Indirect:**")
        errors = self.errors_after(self.text[start:end], "Only 0 direct rivals found (8 searches).\n\n")
        self.assertEqual(errors, [])

    def test_not_researched_cannot_bypass_checks_on_a_web_run(self):
        errors = self.errors_after("- **Timing risk:** hosting platforms bundle one-command deploys",
                                   "- **Timing risk:** a $2B incumbent\n  - Top-down: NOT RESEARCHED")
        self.assertCaught(errors, "says 'NOT RESEARCHED' but dg.web isn't false")
        self.assertCaught(errors, "market figure without")

    def test_local_only_caps_are_enforced(self):
        text = self.text.replace('"web":true', '"web":false').replace(
            "## 2. Market\n", "## 2. Market\n\nNOT RESEARCHED — re-run with web access\n").replace(
            "## 3. Competitive field\n", "## 3. Competitive field\n\nNOT RESEARCHED — re-run with web access\n")
        self.report.write_text(text.replace('"why_now":3', '"why_now":3'))
        errors = check_report.check(self.report)[0]
        self.assertCaught(errors, "dg.subs.why_now is capped at 2")
        self.assertCaught(errors, "confidence must be Low")

    def test_card_confidence_and_stamp_must_match(self):
        data = json.loads((self.tmp / "card.json").read_text())
        data["bigness"]["confidence"] = "High"
        data["date"] = "2026-01-01"
        (self.tmp / "assets" / "strategy-card.svg").write_text(strategy_card.render_svg(data))
        errors = check_report.check(self.report)[0]
        self.assertCaught(errors, "says 'HIGH CONFIDENCE' but the report's confidence is Medium")
        self.assertCaught(errors, "stamped v.* · 2026-01-01")

    def test_malformed_dg_is_an_error_not_a_crash(self):
        for old, new in (('"subs":{"market":2', '"subs":[2],"x":{"market":2'),
                         ('"bigness":12', '"bigness":-1')):
            self.report.write_text(self.text.replace(old, new, 1))
            errors = check_report.check(self.report)[0]
            self.assertTrue(errors)

    def test_sourced_money_figure_needs_no_estimate_label(self):
        errors = self.errors_after("- **Timing risk:** hosting platforms bundle one-command deploys",
                                   "- **Timing risk:** a rival raised $40M ([source](https://example.com/r))")
        self.assertEqual(errors, [])

    def test_euro_figures_are_caught(self):
        errors = self.errors_after("- **Timing risk:** hosting platforms bundle one-command deploys",
                                   "- **Timing risk:** a €2B incumbent bundles deploys")
        self.assertCaught(errors, "market figure without")

    def test_autolinks_are_not_slots(self):
        errors = self.errors_after("- Rivals: [ExampleDeploy](https://example.com/rival)",
                                   "- Rivals: <https://example.com/rival>")
        self.assertEqual(errors, [])

    def test_primary_counted_only_in_call_column(self):
        errors = self.errors_after("| Paid ads | 2 | 1 | 1 | 3 | 7/20 | defer |",
                                   "| Paid ads | 2 | 1 | 1 | 3 | 7/20 | not PRIMARY: defer |")
        self.assertEqual(errors, [])

    def test_card_scores_must_match_report(self):
        data = json.loads((self.tmp / "card.json").read_text())
        data["bigness"]["score"] = 13
        data["bigness"]["breakdown"][0]["score"] = 3  # Market headroom 2 → 3
        (self.tmp / "assets" / "strategy-card.svg").write_text(strategy_card.render_svg(data))
        errors = check_report.check(self.report)[0]
        self.assertCaught(errors, "shows Bigness 13.*re-render")
        self.assertCaught(errors, "Market headroom shows 3/5")

    def test_malformed_version_is_an_error(self):
        text = self.text.replace('{"v":"0.4.0"', '{"v":"dev"').replace(
            "distribution-god v0.4.0", "distribution-god vdev")
        self.report.write_text(text)
        self.assertCaught(check_report.check(self.report)[0], "dg.v must be the plugin version")

    def test_line_budget_follows_the_report_version(self):
        # 480 lines: over the old 450 budget, under v0.4's 500.
        padded = self.text.replace("## Sources", "\n" * (480 - self.text.count("\n")) + "## Sources")
        self.report.write_text(padded)
        self.assertFalse(any("lines;" in w for w in check_report.check(self.report)[1]))
        self.report.write_text(padded.replace('{"v":"0.4.0"', '{"v":"0.3.0"').replace(
            "distribution-god v0.4.0", "distribution-god v0.3.0"))
        self.assertTrue(any("~450" in w for w in check_report.check(self.report)[1]))


class ArithmeticTests(unittest.TestCase):
    CASES = [  # (text, should_pass) — includes the reviewers' reproductions
        ("150–300k × $240–480/yr = $36M–$144M", True),
        ("150–300k × $240–480/yr = $50M–$250M", False),
        ("5.0M × 5% × $60 = $15.0M", True),
        ("Low: 36.5M × 1% ÷ 8 × $1,200 = $54.75M. High: 36.5M × 3% ÷ 8 × $2,400 = $328.5M.", True),
        ("36.5M devs × 1–3% ÷ 8–12 per team × $1,200 = $36.5M–$164.25M", True),
        ("10k teams × $500–$2k/yr = $5M–$20M", True),
        ("~400k teams × ~$25/mo × 12 = ~$120M", True),
        ("10k B2B teams × $500 = $5M", True),
        ("10k B2B teams × $500 = $50M", False),
        ("$14.1M–$406.8M + $10M–$72M = $24.1M–$478.8M", True),
        ("400k teams x $300 = $120M", True),
        ("400k teams x $300–1,200/yr = $12M–$48M", False),
        ("2 million devs × $10 = $20 million", True),
        ("150k × $240 = **$36M**", True),
        ("*Developer seats:* 36.5M × 30.9%–48.3% = 11.28M–17.63M", True),
        ("8 developers per team (assumption) × $1,200 = $9,600", True),
        ("3 Months later, 2 × 3 = 6", True),
        ("$15/user/month × 8 = $1,440", False),
    ]

    def test_cases(self):
        for text, ok in self.CASES:
            with self.subTest(text=text):
                self.assertEqual(check_report.arithmetic_errors(text) == [], ok)

    def test_headroom_bands(self):
        for mid, band in ((39e6, 0), (50e6, 1), (199e6, 1), (240e6, 2), (1e9, 3), (5e9, 4), (20e9, 5)):
            self.assertEqual(check_report.headroom_band(mid), band)


